/**
 * The demo planner, for the offline run-book only.
 *
 * A presenter's real first question is not "what does the console do", it is
 * "what am I allowed to show this buyer, on this date, on their stack". The
 * readiness register answers it and the build schedule constrains it, and
 * until now the answer lived in a spreadsheet nobody opens on the way into a
 * meeting.
 *
 * It is built into dist-runbook/runbook.html and deliberately not into the
 * hosted page. flow.alvarodenicolas.com is a public URL: the planner carries
 * client names, commercial notes and a list of sentences never to say, and
 * none of that belongs on something a client can open. The hosted page gets a
 * line saying where the planner is instead.
 *
 * Everything here is rendered from sources/readiness.private.json, which is
 * generated by scripts/sync-readiness.mjs and gitignored for the same reason.
 */

const escapeHtml = (value) =>
  String(value).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

export const PLANNER_PLACEHOLDER = '__PLANNER__';

/** What the hosted page says in place of the planner. */
export function renderPlannerNotice() {
  return `  <section>
    <div class="section-head">
      <span class="eyebrow">Before you start</span>
      <h2>Can I show it?</h2>
    </div>
    <p>The demo planner — what you may show a given buyer, on a given date, on their
      stack — is in the offline copy of this run-book rather than on this page. It
      quotes clients by name and carries the list of things never to say, and this
      page is on a public address. Download the offline copy from the console and
      keep it on the laptop you present from.</p>
  </section>
`;
}

export function renderPlanner(data) {
  const {
    capabilities = [],
    stacks = [],
    sectors = [],
    anchors = [],
    never = [],
    asOf,
    syncedAt,
    assumptions = {},
  } = data;

  // Only the fields the planner actually renders, so the payload in the page
  // is the smallest thing that does the job rather than the whole register.
  const slim = capabilities.map((c) => ({
    id: c.id,
    name: c.name,
    state: c.state,
    from: c.registerFrom,
    plan: c.planFrom ?? null,
    manual: c.manual ?? null,
    epics: c.epics ?? [],
    what: c.what ?? '',
    evidence: c.evidence ?? '',
    stacks: c.stacks ?? ['*'],
  }));

  /*
   * Source control and cloud are different questions.
   *
   * A capability that names github and bitbucket is saying something about
   * where the pipeline runs; one that names aws and azure is saying where it
   * is deployed. Treated as one list, a buyer who runs GitHub and has not yet
   * said which cloud they use would be told the deployment kit is ruled out,
   * which is false and is the kind of false a seller repeats in a meeting.
   *
   * So each family is answered separately: a capability is ruled out only
   * when the buyer has told us what they run in that family and none of it
   * matches.
   */
  const FAMILY = {
    github: 'scm', bitbucket: 'scm', gitlab: 'scm', 'azure-devops': 'scm',
    aws: 'cloud', azure: 'cloud', gcp: 'cloud',
  };
  const unknown = stacks.map((s) => s.id).filter((id) => !FAMILY[id]);
  if (unknown.length) throw new Error(`the register has stacks this planner cannot place in a family: ${unknown.join(', ')}`);

  const payload = JSON.stringify({
    caps: slim,
    family: FAMILY,
    stacks,
    sectors,
    anchors,
    never,
    asOf,
    syncedAt,
    scheduleEnds: assumptions.Schedule ?? null,
  });

  const stackBoxes = stacks
    .map(
      (s) => `<label class="pl-chip"><input type="checkbox" name="stack" value="${escapeHtml(s.id)}">
          <span>${escapeHtml(s.label)}</span></label>`,
    )
    .join('\n        ');

  const sectorOptions = sectors
    .map((s) => `<option value="${escapeHtml(s.id)}">${escapeHtml(s.label)}</option>`)
    .join('\n          ');

  return `  <section class="planner">
    <div class="section-head">
      <span class="eyebrow">Before you start</span>
      <h2>Can I show it?</h2>
    </div>

    <p>Answer the seller's question before the presenter's one. Set the date of the
      meeting, who is in the room and what they run, and this says what is safe to
      put on screen. It is generated from the readiness register and the build
      schedule, not written here, so it moves when they move.</p>

    <form class="pl-controls" id="pl-form">
      <div class="pl-field">
        <label for="pl-date">Demo date</label>
        <input type="date" id="pl-date" name="date">
      </div>
      <div class="pl-field">
        <label for="pl-sector">Who is in the room</label>
        <select id="pl-sector" name="sector">
          ${sectorOptions}
        </select>
      </div>
      <div class="pl-field pl-field-wide">
        <span class="pl-legend">What they run — tick what is actually theirs</span>
        <div class="pl-chips">
        ${stackBoxes}
        </div>
      </div>
    </form>

    <div id="pl-out" class="pl-out"></div>

    <p class="pl-prov">Register as at <strong>${escapeHtml(asOf)}</strong>, synced
      ${escapeHtml(syncedAt)}. Where the register and the build plan disagree the plan
      is shown beside it, because a date the plan does not reach is not a date.</p>

    <script type="application/json" id="pl-data">${payload.replace(/</g, '\\u003c')}</script>
    <script>
    (() => {
      const D = JSON.parse(document.getElementById('pl-data').textContent);
      const form = document.getElementById('pl-form');
      const out = document.getElementById('pl-out');
      const esc = s => String(s == null ? '' : s).replace(/[&<>"]/g, m => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[m]));
      const MONTHS = ['January','February','March','April','May','June','July','August','September','October','November','December'];
      const month = iso => { if (!iso) return ''; const [y,m] = iso.split('-'); return MONTHS[+m-1] + ' ' + y; };
      const day = iso => { if (!iso) return ''; const [y,m,d] = iso.split('-'); return (+d) + ' ' + MONTHS[+m-1] + ' ' + y; };

      // Ruled out only where the buyer has answered the same question the
      // capability asks. Ticking nothing in a family means we do not know yet,
      // and not knowing is not a reason to strike something off.
      const fits = (cap, chosen) => {
        if (cap.stacks.includes('*') || !chosen.length) return true;
        const families = [...new Set(cap.stacks.map(s => D.family[s]).filter(Boolean))];
        return families.every(f => {
          const theirs = chosen.filter(s => D.family[s] === f);
          if (!theirs.length) return true;
          return cap.stacks.some(s => theirs.includes(s));
        });
      };

      const card = (cap, date) => {
        const late = cap.plan && cap.plan > cap.from && !cap.manual;
        return '<article class="pl-card">' +
          '<h4>' + esc(cap.name) + '</h4>' +
          (cap.what ? '<p>' + esc(cap.what) + '</p>' : '') +
          '<dl>' +
            (cap.state !== 'live' ? '<div><dt>Register</dt><dd>from ' + month(cap.from) + '</dd></div>' : '') +
            (late ? '<div class="pl-late"><dt>Plan</dt><dd>' + month(cap.plan) + ' &middot; ' + esc(cap.epics.join(', ')) +
                '. Do not promise the register date.</dd></div>' : '') +
            (cap.manual ? '<div><dt>By hand</dt><dd>' + esc(cap.manual) + '</dd></div>' : '') +
            (cap.evidence ? '<div><dt>Evidence</dt><dd>' + esc(cap.evidence) + '</dd></div>' : '') +
          '</dl>' +
        '</article>';
      };

      const group = (title, note, caps, date, cls) =>
        '<section class="pl-group ' + cls + '">' +
          '<h3>' + esc(title) + ' <span>' + caps.length + '</span></h3>' +
          '<p class="pl-note">' + esc(note) + '</p>' +
          (caps.length ? caps.map(c => card(c, date)).join('') : '<p class="pl-empty">Nothing on this date.</p>') +
        '</section>';

      function render() {
        const fd = new FormData(form);
        const date = fd.get('date') || new Date().toISOString().slice(0, 10);
        const sector = D.sectors.find(s => s.id === fd.get('sector')) || D.sectors[0];
        const chosen = fd.getAll('stack');

        const usable = D.caps.filter(c => fits(c, chosen));
        const show = usable.filter(c => c.state === 'live' && c.from <= date);
        const maybe = usable.filter(c => c.state === 'build' && c.from <= date);
        const not = usable.filter(c => (c.state === 'build' && c.from > date) || c.state === 'planned');

        // A capability their stack rules out is worth naming rather than
        // silently dropping: it is the difference between "we do not do that"
        // and "not on Azure DevOps, and here is what that costs".
        const blocked = D.caps.filter(c => !fits(c, chosen));

        const gaps = D.stacks.filter(s => chosen.includes(s.id) && s.cover !== 'full');
        const near = D.anchors.filter(a => Math.abs(Date.parse(a.d) - Date.parse(date)) < 12096e5);

        out.innerHTML =
          '<div class="pl-lens">' +
            '<h3>' + esc(sector.label) + '</h3>' +
            '<p class="pl-lead">' + esc(sector.lead) + '</p>' +
            '<p class="pl-warn"><strong>Careful.</strong> ' + esc(sector.warn) + '</p>' +
            '<p class="pl-asks"><strong>They will ask:</strong> ' + sector.asks.map(esc).join(' &middot; ') + '</p>' +
          '</div>' +
          (gaps.length ? '<div class="pl-lens pl-stackwarn"><h3>Their stack</h3>' +
            gaps.map(g => '<p><strong>' + esc(g.label) + '</strong> — ' + esc(g.note) + '</p>').join('') + '</div>' : '') +
          (near.length ? '<div class="pl-lens"><h3>Competing for the same people</h3>' +
            near.map(a => '<p><strong>' + day(a.d) + ' &middot; ' + esc(a.label) + '</strong> (' + esc(a.who) + ') — ' + esc(a.note) + '</p>').join('') + '</div>' : '') +
          '<div class="pl-cols">' +
            group('Show this', 'Running, paid for, and demonstrable on the day.', show, date, 'pl-yes') +
            group('Only if it lands', 'In build and dated before the meeting. Check it is actually working the morning of, and quote the plan date rather than the register date where they differ.', maybe, date, 'pl-maybe') +
            group('Do not show', 'Not dated to be there yet. Describe it as intent if asked, never as a demo.', not, date, 'pl-no') +
          '</div>' +
          (blocked.length ? '<div class="pl-lens pl-stackwarn"><h3>Their stack rules these out</h3><p>' +
            blocked.map(c => esc(c.name)).join(' &middot; ') + '</p></div>' : '') +
          '<div class="pl-never"><h3>Never say, whatever the date</h3><ul>' +
            D.never.map(n => '<li>' + esc(n) + '</li>').join('') + '</ul></div>';
      }

      form.addEventListener('input', render);
      form.querySelector('#pl-date').value = new Date().toISOString().slice(0, 10);
      render();
    })();
    </script>
  </section>
`;
}

